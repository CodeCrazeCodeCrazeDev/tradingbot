"""
Automated Duplicate and Tier-0 Architecture Audit Tool
======================================================
Scans the AlphaAlgo repository to detect duplicate Tier-0 subsystems:
Controllers, Event Buses, Memory Systems, Registries, Planners, and Risk Engines.
"""

import os
import ast
from typing import Dict, List, Set, Tuple

# Categories to audit
CATEGORIES = {
    "CognitiveSystemController": ["CognitiveSystemController", "OneBrainController", "CentralController"],
    "DecisionBus": ["UnifiedDecisionBus", "EventBus", "DecisionBus", "UnifiedEventBus"],
    "MemorySystem": ["HierarchicalMemorySystem", "MemoryOS", "CognitiveMemoryOS", "SAGEGraphMemory", "MemorySystem"],
    "RiskEngine": ["UnifiedRiskEngine", "RiskManager", "MASTER_risk_manager"],
    "Registry": ["UnifiedComponentRegistry", "UnifiedRegistry", "SkillRegistry", "SystemRegistry"],
    "WorldModel": ["WorldModel", "MockWorldModel", "DeterministicWorldModel", "CausalWorldModel"]
}

def analyze_file(filepath: str) -> Tuple[List[str], List[str]]:
    """Extracts defined classes and imported modules/names from a python file."""
    classes = []
    imports = []
    try:
        with open(filepath, 'r', encoding='utf-8', errors='ignore') as f:
            node = ast.parse(f.read(), filename=filepath)

        for n in ast.walk(node):
            if isinstance(n, ast.ClassDef):
                classes.append(n.name)
            elif isinstance(n, ast.Import):
                for name in n.names:
                    imports.append(name.name)
            elif isinstance(n, ast.ImportFrom):
                if n.module:
                    imports.append(n.module)
    except Exception:
        pass
    return classes, imports

def run_audit(root_dir: str = "trading_bot") -> Dict[str, List[Tuple[str, str]]]:
    results = {cat: [] for cat in CATEGORIES}

    for root, _, files in os.walk(root_dir):
        # Skip archive directories to focus on active codebase
        if "_archive" in root:
            continue
        for file in files:
            if file.endswith(".py"):
                filepath = os.path.join(root, file)
                classes, imports = analyze_file(filepath)

                for cls in classes:
                    for cat, keywords in CATEGORIES.items():
                        for kw in keywords:
                            if kw.lower() in cls.lower():
                                results[cat].append((filepath, cls))
                                break
    return results

def generate_report(results: Dict[str, List[Tuple[str, str]]]):
    report = []
    report.append("# Tier-0 Architectural Duplication & Ownership Report\n")
    report.append("Generated by `tools/detect_duplicates.py` during Production Engineering Audit.\n")

    canonical_map = {
        "CognitiveSystemController": "trading_bot/core/csc/controller.py (CognitiveSystemController)",
        "DecisionBus": "trading_bot/core/unified_event_bus.py (UnifiedDecisionBus)",
        "MemorySystem": "trading_bot/core/hms/memory.py (HierarchicalMemorySystem)",
        "RiskEngine": "trading_bot/core/risk/unified_risk_engine.py (UnifiedRiskEngine)",
        "Registry": "trading_bot/core/unified_registry.py (UnifiedComponentRegistry)",
        "WorldModel": "trading_bot/core/phce_d_engine.py (PHCE-D parallel engine) & tests/test_world_model.py (MockWorldModel)"
    }

    for cat, matches in results.items():
        report.append(f"## Category: {cat}")
        report.append(f"**Canonical Implementation:** `{canonical_map[cat]}`\n")
        report.append("### Detected Variants & Duplicates:")
        if not matches:
            report.append("- *No active duplicates found outside archived folders.*\n")
            continue

        # Deduplicate matches
        unique_matches = sorted(list(set(matches)))
        for filepath, cls in unique_matches:
            is_canonical = canonical_map[cat].split(" ")[0] in filepath
            status = "CANONICAL" if is_canonical else "REDUNDANT/DUPLICATE"
            report.append(f"- `{filepath}`: Class `{cls}` (**{status}**)")

        report.append("\n### Consolidation Roadmap & Migration Plan:")
        if len(unique_matches) > 1:
            report.append("1. **Deprecate Redundant Implementations**: Mark duplicate classes as deprecated with warning triggers.")
            report.append("2. **Reroute Importers**: Repoint all active imports to canonical Tier-0 pathways.")
            report.append("3. **Remove & Consolidate**: Permanently delete redundant components in favor of clean architecture.")
        else:
            report.append("- *Consolidation achieved. Singular Tier-0 implementation maintained on the active path.*")
        report.append("\n" + "-"*40 + "\n")

    os.makedirs("SCIENTIFIC_FOUNDATION_2026", exist_ok=True)
    report_path = "SCIENTIFIC_FOUNDATION_2026/07_COMPONENT_MAPPING.md"
    with open(report_path, 'w', encoding='utf-8') as f:
        f.write("\n".join(report))
    print(f"Audit complete! Report written to {report_path}")

if __name__ == "__main__":
    audit_results = run_audit()
    generate_report(audit_results)
