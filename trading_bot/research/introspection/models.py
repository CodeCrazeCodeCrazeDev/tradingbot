from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Dict, List


@dataclass
class ReasoningHop:
    """Represents a discrete step or node in an agentic reasoning chain."""
    step_id: int
    step_title: str
    evidence_claims: List[str]
    confidence_score: float  # 0.0 to 1.0
    entropy: float           # Shannon entropy of the step's prediction/prob state
    vfe_surprise: float      # Variational Free Energy surprise score for this step


@dataclass
class AnomalyDiagnosis:
    """Anomalous reasoning or inconsistent evidence flag details."""
    is_anomalous: bool
    description: str
    anomaly_type: str        # e.g., "EVIDENCE_INCONSISTENCY", "VFE_SURPRISE_SPIKE", "PLANNING_LOOP"
    severity_pct: float      # Severity percentage


@dataclass
class IntrospectionReport:
    """The structured self-diagnostic introspection report generated by the engine."""
    report_id: str
    target_decision_id: str
    overall_confidence: float     # Calibrated confidence score between 0.0 and 1.0
    reasoning_hops_evaluated: int
    anomalies: List[AnomalyDiagnosis]
    is_decision_safe: bool         # Gate signal to block or execute order
    evidence_consistency_score: float
    decision_quality_explanation: str
    created_at: datetime = field(default_factory=datetime.utcnow)
